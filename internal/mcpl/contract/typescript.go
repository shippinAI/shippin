package contract

import (
	"bytes"
	"fmt"
	"strings"
)

// typeScript is the panel's action map: every action's route and rules, the types it takes and
// returns, and the arguments callAction needs for it.
func typeScript(m *model, ops []op) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/mcplspec from the action registry. DO NOT EDIT.\n// Change the action's Go types and run `go generate ./internal/actions`.\n\n")
	for _, n := range sortedNames(m) {
		if d := m.defs[n]; d.kind == "enum" {
			fmt.Fprintf(&b, "export type %s = %s;\n\n", n, ts(d, ""))
		} else {
			fmt.Fprintf(&b, "export type %s = %s;\n\n", n, tsObject(d, "  ", ""))
		}
	}
	// Only the route reaches the bundle: it is all callAction needs, and the bundle stays small however
	// many actions there are. Everything else is in the types (free at run time), the OpenAPI document
	// and GET /v1/mcpl.
	b.WriteString("/** Each action's route, \"METHOD /path\": all callAction needs at run time. */\nexport const routes = {\n")
	for _, o := range ops {
		fmt.Fprintf(&b, "  %q: %q,\n", o.g.ID, o.g.Route)
	}
	b.WriteString("} as const;\n\nexport type ActionId = keyof typeof routes;\n\n")
	b.WriteString("/** What each action takes and returns (`args` are callAction's arguments after the ID), its risk,\n * and the event it emits. Types only: none of this is in the bundle. */\nexport type ActionTypes = {\n")
	for _, o := range ops {
		ev := "never"
		if o.g.Event != "" {
			ev = fmt.Sprintf("%q", o.g.Event)
		}
		fmt.Fprintf(&b, "  %q: { args: %s; output: %s; risk: %q; event: %s };\n", o.g.ID, args(m, o), output(o), o.g.Risk, ev)
	}
	b.WriteString("};\n")
	return b.Bytes()
}

func args(m *model, o op) string {
	params := "Record<string, never>"
	paramsRequired := len(o.path) > 0
	if len(o.path)+len(o.query) > 0 {
		var fs []string
		for _, p := range o.path {
			fs = append(fs, p+": string")
		}
		for _, q := range o.query {
			fs = append(fs, q+"?: string")
		}
		params = "{ " + strings.Join(fs, "; ") + " }"
	}
	if !o.reason {
		if paramsRequired {
			return "[params: " + params + "]"
		}
		return "[params?: " + params + "]"
	}
	reason := "{ reason?: string }"
	if o.g.Reason {
		reason = "{ reason: string }"
	}
	body := reason
	if o.body != nil {
		body = ts(o.body, "") + " & " + reason
	}
	switch req := m.bodyRequired(o); {
	case req:
		return "[params: " + params + ", body: " + body + "]"
	case paramsRequired:
		return "[params: " + params + ", body?: " + body + "]"
	default:
		return "[params?: " + params + ", body?: " + body + "]"
	}
}

func output(o op) string {
	if o.output == nil {
		return "void"
	}
	return ts(o.output, "")
}

func ts(n *node, indent string) string {
	switch n.kind {
	case "string", "date-time", "bytes":
		return "string"
	case "enum":
		q := make([]string, len(n.values))
		for i, v := range n.values {
			q[i] = fmt.Sprintf("%q", v)
		}
		return strings.Join(q, " | ")
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "array":
		e := ts(n.elem, indent)
		if strings.ContainsAny(e, " |&") && !strings.HasPrefix(e, "{") {
			e = "(" + e + ")"
		}
		return e + "[]"
	case "map":
		return "Record<string, " + ts(n.elem, indent) + ">"
	case "ref":
		return n.ref
	case "object":
		return tsObject(n, "", indent)
	}
	return "unknown"
}

// tsObject writes an object on one line, or one field per line when step is set.
func tsObject(n *node, step, indent string) string {
	if len(n.fields) == 0 {
		return "Record<string, never>"
	}
	parts := make([]string, 0, len(n.fields))
	for _, f := range n.fields {
		t := ts(f.n, indent+step)
		if f.nullable {
			t += " | null"
		}
		opt := ""
		if f.optional {
			opt = "?"
		}
		parts = append(parts, fmt.Sprintf("%s%s: %s", key(f.name), opt, t))
	}
	if step == "" {
		return "{ " + strings.Join(parts, "; ") + " }"
	}
	return "{\n" + indent + step + strings.Join(parts, ";\n"+indent+step) + ";\n" + indent + "}"
}

// key quotes a property name that is not a plain identifier.
func key(s string) string {
	for i, r := range s {
		if !(r == '_' || r == '$' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || i > 0 && r >= '0' && r <= '9') {
			return fmt.Sprintf("%q", s)
		}
	}
	return s
}
